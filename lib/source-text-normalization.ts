export function normalizeNonSubstantiveSourceText(value: string): string {
  return value
    .replace(/列印時間：?\s*\d{2,3}\/\d{1,2}\/\d{1,2}\s+\d{1,2}:\d{2}/g, "列印時間")
    .replace(/專區瀏覽人次\s*累計[\d,]+\s*今日[\d,]+/g, "專區瀏覽人次")
    .replace(/累計瀏覽人次：?[\d,]+\s*今日瀏覽人次：?[\d,]+/g, "瀏覽人次")
    .replace(/(點閱人氣|點閱次數|點閱數|瀏覽人數|瀏覽人次|觀看數|下載次數)\s*[:：]?\s*[\d,]+(?:\s*(?:人|次))?/g, "$1")
    .replace(/((?:pdf\s*)?下載)\s*[\d,]+\s*次/gi, "$1")
    .replace(/((?:(?:最後|資料|網頁)?更新日期|資料更新|資料檢視|檢核日期))\s*[:：]?\s*(?:\d{2,3}|\d{4})(?:[./-]\d{1,2}[./-]\d{1,2}|年\d{1,2}月\d{1,2}日?)(?:\s+\d{1,2}:\d{2}(?::\d{2})?)?/g, "$1")
    .replace(/您來自：\s*[0-9a-f:.]+/gi, "您來自");
}
